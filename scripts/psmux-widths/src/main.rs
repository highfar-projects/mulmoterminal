// Prints every codepoint from U+00A0 up whose `UnicodeWidthChar::width` is not 1, as the
// [first, last, width] runs common/tmuxWidthTable.ts reads. Below U+00A0 the width is fixed by
// cellWidthOf, and surrogates are not chars.
use unicode_width::UnicodeWidthChar;

const FIRST: u32 = 0xa0;
const LAST: u32 = 0x10ffff;
const UNICODE_WIDTH_VERSION: &str = "0.2.2";

// psmux's grid places anything wider than one column as one wide cell (Cell::set_wide on `> 1`, and
// Screen::text advances two columns), so U+17D8's width of 3 occupies two.
fn width_of(cp: u32) -> u8 {
    match char::from_u32(cp) {
        Some(c) => c.width().map_or(0, |w| w.min(2) as u8),
        None => 1,
    }
}

fn main() {
    let mut runs: Vec<(u32, u32, u8)> = Vec::new();
    for cp in FIRST..=LAST {
        let w = width_of(cp);
        if w == 1 {
            continue;
        }
        match runs.last_mut() {
            Some(last) if last.1 + 1 == cp && last.2 == w => last.1 = cp,
            _ => runs.push((cp, cp, w)),
        }
    }
    println!("// Generated by scripts/psmux-widths from unicode-width {UNICODE_WIDTH_VERSION}, the crate psmux 3.4.0 counts");
    println!("// columns with (crates/vt100-psmux/src/width.rs). Do not edit; regenerate when psmux moves the crate.");
    println!("import type {{ WidthRun }} from \"./tmuxWidthTable.js\";");
    println!();
    println!("export const PSMUX_UNICODE_WIDTH_VERSION = \"{UNICODE_WIDTH_VERSION}\";");
    println!();
    println!("export const PSMUX_WIDTH_RUNS: readonly WidthRun[] = [");
    for (first, last, w) in &runs {
        println!("  [0x{first:x}, 0x{last:x}, {w}],");
    }
    println!("];");
}
